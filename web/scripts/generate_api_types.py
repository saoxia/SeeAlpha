"""Generate the small set of frontend response types from FastAPI OpenAPI."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

WEB_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(WEB_ROOT.parent))

from api.main import app

OUTPUT_PATH = WEB_ROOT / "app" / "api" / "generated" / "schema.ts"
SCHEMA_NAMES = (
    "ChartCandle",
    "LocalChartResponse",
    "ManualOrderView",
    "ManualPosition",
    "ManualBalance",
    "ManualInstrument",
    "ManualStateResponse",
    "ManualMarketSummary",
    "ManualMarketsResponse",
    "ManualOrderRequest",
    "ManualCancelRequest",
    "ManualOrderResponse",
    "ExchangeAccountCreateRequest",
    "ExchangeAccountUpdateRequest",
    "ExchangeAccountResponse",
    "DataCapabilities",
    "DataPolicy",
    "DataPolicySave",
    "PairDeletePlanRequest",
    "PairDeleteRequest",
    "DataMarket",
    "DataDeletionPlan",
    "DataJobResponse",
    "EquityRebuildRequest",
    "EquityRebuildResponse",
    "EquityCandleResponse",
    "EquityCandleSeriesResponse",
    "ExchangeAccountNavigationResponse",
    "ExchangeAccountSummaryResponse",
    "ExchangePortfolioResponse",
    "ExchangeAssetResponse",
    "ExchangePositionResponse",
    "ExchangeTradeResponse",
)
PRIMITIVES = {
    "boolean": "boolean",
    "integer": "number",
    "number": "number",
    "string": "string",
    "null": "null",
}


def _typescript_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return f'components["schemas"]["{schema["$ref"].rsplit("/", 1)[-1]}"]'
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_typescript_type(item) for item in schema["anyOf"]))
    if "oneOf" in schema:
        return " | ".join(dict.fromkeys(_typescript_type(item) for item in schema["oneOf"]))

    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        return " | ".join(PRIMITIVES.get(item, "unknown") for item in schema_type)
    if schema_type == "array":
        item = _typescript_type(schema.get("items", {}))
        return f"({item})[]" if " | " in item else f"{item}[]"
    if schema_type == "object":
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {_typescript_type(additional)}>"
        return "Record<string, unknown>"
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    return PRIMITIVES.get(schema_type, "unknown")


def _schema_block(name: str, schema: dict[str, Any]) -> list[str]:
    required = set(schema.get("required", []))
    lines = [f"      {name}: {{"]
    for property_name, property_schema in schema.get("properties", {}).items():
        optional = "" if property_name in required else "?"
        lines.append(f"        {property_name}{optional}: {_typescript_type(property_schema)};")
    lines.append("      };")
    return lines


def main() -> None:
    all_schemas = app.openapi()["components"]["schemas"]
    missing = sorted(set(SCHEMA_NAMES) - set(all_schemas))
    if missing:
        raise RuntimeError(f"OpenAPI schemas missing: {', '.join(missing)}")

    lines = [
        "/**",
        " * Generated by scripts/generate_api_types.py from FastAPI OpenAPI.",
        " * Do not edit this file directly.",
        " */",
        "export interface components {",
        "  schemas: {",
    ]
    for name in SCHEMA_NAMES:
        lines.extend(_schema_block(name, all_schemas[name]))
    lines.extend(["  };", "}", ""])

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Frontend API types generated at {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
